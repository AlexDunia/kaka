import fs from 'node:fs'

const tokens = JSON.parse(fs.readFileSync('src/design-system/tokens.json', 'utf8'))
const declarations = []
for (const group of ['color', 'space', 'radius', 'font', 'size', 'weight', 'rhythm']) {
  for (const [name, value] of Object.entries(tokens[group])) declarations.push(`  --ds-${group}-${name}: ${value};`)
}
const aliases = []
for (const group of ['color', 'space', 'radius', 'font', 'size', 'weight']) {
  for (const name of Object.keys(tokens[group])) aliases.push(`  --rh-${group}-${name}: var(--ds-${group}-${name});`)
}
fs.writeFileSync('src/styles/design-tokens.css', `/* Generated by scripts/build-design-tokens.mjs from src/design-system/tokens.json. */\n:root {\n${declarations.join('\n')}\n}\n#app, #app :is(.public-site, .event-profile, .event-workspace, .app-container) {\n${aliases.join('\n')}\n}\n`)
console.log('Generated shared Rush Hour design tokens.')
